import unittest
from ohlp_parser import split_ohlp_sections

SAMPLE_TEXT = '''6.3 Срок годности 
2 года 
Не применять по истечении срока годности. 
6.4 Особые меры предосторожности при хранении 
В защищенном от света месте при температуре не выше 25 °С.  
Не замораживать! 
Хранить в недоступном для детей месте!  
6.5 Форма выпуска и упаковка 
По 100 мл, 200 мл и 300 мл препарата во флаконы из полипропилена с градуировкой 
100 (для объема 100 мл), 200 (для объема 200 мл), 300 (для объема 400 мл) с петлей – 
держателем, укупоренные полипропиленовыми крышками с резиновой подкладкой и 
снабженные колпачком с отрывным кольцом для вскрытия, наваренным на флакон. 
По 1 флакону с инструкцией по медицинскому применению на государственном и 
русском языках помещают в картонную пачку или 30, 40, 120 флаконов вместе с 
инструкцией по применению на государственном и русском языках помещают в 
коробку картонную (групповая). 
6.6 
Особые меры предосторожности при уничтожениииспользованного 
лекарственного препарата или отходов, полученныхпосле применения 
лекарственного препарата или работы с ним. 
Сбор, обеззараживание, временное хранение, транспортирование, уничтожение и 
утилизацию использованных инфузий однократного применения осуществляют в 
соответствии с Санитарными правилами «Санитарно-эпидемиологические требования 
к сбору, использованию, применению, обезвреживанию, транспортировке, хранению и 
захоронению отходов производства и потребления»). 
6.7 Условия отпуска из аптек 
По рецепту 
7. ДЕРЖАТЕЛЬ РЕГИСТРАЦИОННОГО УДОСТОВЕРЕНИЯ 
'''

SECTIONS = [
    "6. ФАРМАЦЕВТИЧЕСКИЕ СВОЙСТВА",
    "6.1 Перечень вспомогательных веществ",
    "6.2 Несовместимость",
    "6.3 Срок годности (срок хранения)",
    "6.4 Особые меры предосторожности при хранении",
    "6.5 Характер и содержание первичной упаковки",
    "6.6 Особые меры предосторожности при уничтожении использованного лекарственного препарата или отходов, полученных после применения лекарственного препарата, и другие манипуляции с препаратом",
    "7. ДЕРЖАТЕЛЬ РЕГИСТРАЦИОННОГО УДОСТОВЕРЕНИЯ",
]

class TestOhlpParserHybridBehavior(unittest.TestCase):
    def test_fragment_is_split_without_losses_and_duplicates(self):
        blocks = split_ohlp_sections(SAMPLE_TEXT, SECTIONS, threshold=0.6)

        # 6.3: срок годности должен быть, но хранение — нет
        part_63 = blocks.get("6.3 Срок годности (срок хранения)", "")
        self.assertIn("2 года", part_63)
        self.assertIn("Не применять по истечении срока годности", part_63)
        self.assertNotIn("В защищенном от света месте", part_63)

        # 6.4: только текст про хранение
        part_64 = blocks.get("6.4 Особые меры предосторожности при хранении", "")
        self.assertIn("В защищенном от света месте при температуре не выше 25 °С", part_64)
        self.assertIn("Не замораживать", part_64)
        self.assertIn("Хранить в недоступном для детей месте", part_64)

        # 6.5: должно выделиться, даже с чужим заголовком
        part_65 = blocks.get("6.5 Характер и содержание первичной упаковки", "")
        self.assertIn("По 100 мл, 200 мл и 300 мл препарата", part_65)
        self.assertIn("полипропиленовыми крышками", part_65)

        # 6.6: включает утилизацию и "левый" 6.7 с текстом "По рецепту"
        part_66 = blocks.get("6.6 Особые меры предосторожности при уничтожении использованного лекарственного препарата или отходов, полученных после применения лекарственного препарата, и другие манипуляции с препаратом", "")
        self.assertIn("Сбор, обеззараживание, временное хранение, транспортирование, уничтожение", part_66)
        self.assertIn("6.7 Условия отпуска из аптек", part_66)
        self.assertIn("По рецепту", part_66)

        # 7: нет контента в рамках данного фрагмента (только заголовок)
        part_7 = blocks.get("7. ДЕРЖАТЕЛЬ РЕГИСТРАЦИОННОГО УДОСТОВЕРЕНИЯ", "")
        self.assertEqual(part_7, "")

        # Проверка на отсутствие дубликатов: общий объём блоков не больше исходного
        total_len = sum(len(v) for v in blocks.values())
        self.assertLessEqual(total_len, len(SAMPLE_TEXT))

if __name__ == '__main__':
    unittest.main()
